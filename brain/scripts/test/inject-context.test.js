'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'inj-'));
fs.mkdirSync(path.join(TMP, 'brain', '_index'), { recursive: true });
fs.writeFileSync(path.join(TMP, 'brain', '_index', 'BRAIN.md'), '# BRAIN\nhello brain\n');
fs.writeFileSync(path.join(TMP, 'brain', '_index', 'SESSION.md'), '# SESSION\n');
process.env.AOS_VAULT = TMP;
const { markerPath } = require('../lib/markers.js');
const SCRIPT = path.join(__dirname, '..', 'inject-context.js');
const SID = `t-${process.pid}`;

function run() {
  return spawnSync(process.execPath, [SCRIPT], {
    input: JSON.stringify({ session_id: SID }), encoding: 'utf8',
    env: { ...process.env, AOS_VAULT: TMP, AOS_CONFIG: path.join(TMP, 'none.json') },
  });
}

test('first turn injects brain context and writes its marker to tmpdir, not brain/_index', () => {
  try { fs.unlinkSync(markerPath(`.injected-${SID}`)); } catch {}
  const r = run();
  assert.equal(r.status, 0);
  assert.match(r.stdout, /<brain-context>/);
  assert.match(r.stdout, /hello brain/);
  assert.ok(fs.existsSync(markerPath(`.injected-${SID}`)));
  assert.ok(!fs.readdirSync(path.join(TMP, 'brain', '_index')).some((n) => n.startsWith('.injected-')));
});

test('second turn of the same session injects nothing', () => {
  const r = run();
  assert.equal(r.status, 0);
  assert.equal(r.stdout, '');
});

test('a Codex rollout with a user turn already in it counts as a started session: nothing injected', () => {
  const sid = `cx-${process.pid}`;
  try { fs.unlinkSync(markerPath(`.injected-${sid}`)); } catch {}
  const r = spawnSync(process.execPath, [SCRIPT], {
    input: JSON.stringify({ session_id: sid, transcript_path: path.join(__dirname, 'fixtures', 'codex-rollout.jsonl'), hook_event_name: 'UserPromptSubmit' }),
    encoding: 'utf8',
    env: { ...process.env, AOS_VAULT: TMP, AOS_CONFIG: path.join(TMP, 'none.json'), AOS_HOST: 'codex' },
  });
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stdout, '');
  assert.ok(fs.existsSync(markerPath(`.injected-${sid}`)));
});

test('an empty Codex rollout path injects on the first prompt like Claude does', () => {
  const sid = `cx0-${process.pid}`;
  try { fs.unlinkSync(markerPath(`.injected-${sid}`)); } catch {}
  const r = spawnSync(process.execPath, [SCRIPT], {
    input: JSON.stringify({ session_id: sid, transcript_path: path.join(TMP, 'no-such-rollout.jsonl') }),
    encoding: 'utf8',
    env: { ...process.env, AOS_VAULT: TMP, AOS_CONFIG: path.join(TMP, 'none.json'), AOS_HOST: 'codex' },
  });
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /<brain-context>/);
});

// The secondary safety counts only prompts the user typed before this one (lib/transcript.js isRealPrompt). Claude Code
// starts a session after /clear with its local-command caveat (isMeta) and the command envelope, and may already have
// written the prompt being submitted: neither is an earlier prompt, so the first prompt is injected.
const CLAUDE_CLEAR = [
  { type: 'user', isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>' } },
  { type: 'user', message: { role: 'user', content: '<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>' } },
  { type: 'user', message: { role: 'user', content: '<local-command-stdout></local-command-stdout>' } },
];
const typed = (text) => ({ type: 'user', message: { role: 'user', content: text } });
const answer = (text) => ({ type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text }] } });
const toolResult = { type: 'user', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }] } };

function runWith(sid, entries, prompt, env = {}) {
  try { fs.unlinkSync(markerPath(`.injected-${sid}`)); } catch {}
  const tp = path.join(TMP, `${sid}.jsonl`);
  fs.writeFileSync(tp, entries.map((e) => JSON.stringify(e)).join('\n') + '\n');
  return spawnSync(process.execPath, [SCRIPT], {
    input: JSON.stringify({ session_id: sid, transcript_path: tp, prompt, hook_event_name: 'UserPromptSubmit' }), encoding: 'utf8',
    env: { ...process.env, AOS_VAULT: TMP, AOS_CONFIG: path.join(TMP, 'none.json'), ...env },
  });
}

test('a Claude Code session started after /clear is injected on its first prompt, and logs its usage rows (brain-hub D9)', () => {
  fs.mkdirSync(path.join(TMP, 'brain', 'memory', 'user'), { recursive: true });
  fs.writeFileSync(path.join(TMP, 'brain', 'memory', 'user', 'profile.md'), '# Profile\n');
  fs.writeFileSync(path.join(TMP, 'brain', '_index', 'brain-sources.json'), JSON.stringify({ schema: 1, sections: { who: { paths: ['brain/memory/user/profile.md'] } } }));
  const usage = path.join(TMP, 'brain', '_index', 'memory-usage.jsonl');
  try { fs.unlinkSync(usage); } catch {}
  const r = runWith(`clr-${process.pid}`, CLAUDE_CLEAR, 'what changed since yesterday?', { AOS_HOST: 'claude' });
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /<brain-context>/);
  const rows = fs.readFileSync(usage, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
  assert.deepEqual(rows.map((x) => [x.host, x.how, x.path]), [['claude', 'injected', 'brain/memory/user/profile.md']]);
});

test('a first prompt already in the transcript, or a slash command, is not an earlier prompt: injected', () => {
  const now = runWith(`cur-${process.pid}`, [...CLAUDE_CLEAR, typed('  what changed\nsince yesterday? ')], 'what changed since yesterday?');
  assert.match(now.stdout, /<brain-context>/);
  const cmd = runWith(`cmd-${process.pid}`, [{ type: 'user', message: { role: 'user', content: '<command-message>wrap</command-message>\n<command-name>/wrap</command-name>' } }], '/wrap');
  assert.match(cmd.stdout, /<brain-context>/);
});

test('a session with a prompt typed before this one gets nothing, tool results and envelopes aside', () => {
  const sid = `two-${process.pid}`;
  const r = runWith(sid, [...CLAUDE_CLEAR, typed('first question'), answer('an answer'), toolResult, typed('second question')], 'second question');
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stdout, '');
  assert.ok(fs.existsSync(markerPath(`.injected-${sid}`)));
});

test('a Codex rollout holding only its injected context and this prompt is injected', () => {
  const roll = [
    { type: 'session_meta', payload: { id: 'cx-first', cwd: '/srv/proj', source: 'cli' } },
    { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '<environment_context>\n  <cwd>/srv/proj</cwd>\n</environment_context>' }] } },
    { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: 'list my open todos' }] } },
  ];
  const r = runWith(`cxf-${process.pid}`, roll, 'list my open todos', { AOS_HOST: 'codex' });
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /<brain-context>/);
});

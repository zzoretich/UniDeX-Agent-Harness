#!/usr/bin/env node
'use strict';
/**
 * bump-version.js — keep every version surface in lockstep with ONE product version:
 *   package.json                    .version          (repo version — the source of truth;
 *                                                      cli/plugin-manifests.test.js pins plugin.json to it)
 *   brain/scripts/package.json      .version          (the vendored runtime; the MCP server reports it)
 *   obsidian-plugin/package.json    .version          (the HUD's source; the app reads its version)
 *   plugin/.claude-plugin/plugin.json          .version          (Claude Code plugin)
 *   .claude-plugin/marketplace.json            .plugins[name=agenticos].version
 *   codex-plugin/.codex-plugin/plugin.json     .version          (Codex plugin; generated by tools/build-codex-plugin.js,
 *                                                                 which reads package.json, so a bump and a rebuild agree)
 *   app/package.json                .version          (the UniDeX app)
 *   package-lock.json               .version, .packages[""].version, .packages["obsidian-plugin"].version and, when the
 *                                   lock lists it, .packages["brain/scripts"].version — checked, never written (refresh
 *                                   with npm install --package-lock-only --ignore-scripts)
 *   app/package-lock.json           .version, .packages[""].version — checked, never written (the same install, in app/)
 * The Obsidian plugin's manifest.json and versions.json are gone with its packaging (1.0): the app owns the HUD's id.
 * A bump also rolls CHANGELOG.md's [Unreleased] into `## [x.y.z] — <today>` (tools/changelog.js roll; a no-op when that
 * section exists), and fails when [Unreleased] is empty: a release says what changed.
 * What's new (tour C13): a bump to x.y.z first needs a `releases` entry for it in obsidian-plugin/src/tour/whatsnew.json
 * (the card the app shows on its first launch after the update), or it fails and writes nothing. So the entry is
 * written with the CHANGELOG, before `npm run version:bump` (docs/app-smoke.md, Release procedure). Every release needs
 * one, patches included: `"entries": []` says nothing in it needs a card (the HUD shows no card for an empty release),
 * which keeps that a decision rather than an omission. The version is matched on x.y.z, as the HUD compares versions,
 * so 2.0.0's entry also covers 2.0.0-rc.1. --check asks the same, so release.yml refuses a tag without one.
 * Usage: node tools/bump-version.js <x.y.z> [--check]
 *   --check: exit 1 if any surface differs from <x.y.z>, or whatsnew.json has no release for it (release.yml runs this
 *   against the tag).
 * Exit: 0 ok · 1 mismatch or no What's new release (--check), no What's new release or nothing in [Unreleased] to
 * release (bump) · 2 usage
 */
const fs = require('fs');
const path = require('path');

const SEMVER = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
const FILES = [
  'package.json',
  'brain/scripts/package.json',
  'obsidian-plugin/package.json',
  'plugin/.claude-plugin/plugin.json',
  '.claude-plugin/marketplace.json',
  'codex-plugin/.codex-plugin/plugin.json',
  'app/package.json',
];

const WHATSNEW = 'obsidian-plugin/src/tour/whatsnew.json';

function readJson(p) { return JSON.parse(fs.readFileSync(p, 'utf8')); }
function writeJson(p, obj) { fs.writeFileSync(p, JSON.stringify(obj, null, 2) + '\n'); }

function versionOf(rel, obj) {
  if (rel.endsWith('marketplace.json')) return (obj.plugins || []).find((p) => p.name === 'agenticos')?.version;
  return obj.version;
}

function apply(rel, obj, version) {
  if (rel.endsWith('marketplace.json')) {
    const entry = (obj.plugins || []).find((p) => p.name === 'agenticos');
    if (entry) entry.version = version;
    return obj;
  }
  obj.version = version;
  return obj;
}

function bumpFiles(root, version) {
  if (!SEMVER.test(version)) throw new Error(`not a semver version: ${version}`);
  const out = { updated: [], skipped: [] };
  for (const rel of FILES) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) { out.skipped.push(rel); continue; }
    writeJson(abs, apply(rel, readJson(abs), version));
    out.updated.push(rel);
  }
  return out;
}

function checkFiles(root, version) {
  const bad = [];
  for (const rel of FILES) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) continue;
    const have = versionOf(rel, readJson(abs));
    if (have !== version) bad.push(`${rel}: ${have ?? '(none)'} != ${version}`);
  }
  // package-lock.json is the last surface. bumpFiles never writes it (npm owns the lock's
  // format; `npm install --package-lock-only --ignore-scripts` refreshes it after a bump), but
  // --check must see it: release.yml's first step is `npm ci`, which trips on a stale lock.
  const lockPath = path.join(root, 'package-lock.json');
  if (fs.existsSync(lockPath)) {
    const lock = readJson(lockPath);
    const fields = [
      ['version', lock.version],
      ['packages[""].version', lock.packages && lock.packages[''] && lock.packages[''].version],
      ['packages["obsidian-plugin"].version', lock.packages && lock.packages['obsidian-plugin'] && lock.packages['obsidian-plugin'].version],
    ];
    if (lock.packages && lock.packages['brain/scripts']) fields.push(['packages["brain/scripts"].version', lock.packages['brain/scripts'].version]);
    for (const [name, have] of fields) {
      if (have !== version) bad.push(`package-lock.json (${name}): ${have ?? '(none)'} != ${version}`);
    }
  }
  // The app has its own lockfile (app/ is not a workspace, so runtime installs never pull Electron). Same rule: npm
  // writes it (`npm install --package-lock-only --ignore-scripts` in app/), --check reads it.
  const appLockPath = path.join(root, 'app/package-lock.json');
  if (fs.existsSync(appLockPath)) {
    const lock = readJson(appLockPath);
    for (const [name, have] of [['version', lock.version], ['packages[""].version', lock.packages && lock.packages[''] && lock.packages[''].version]]) {
      if (have !== version) bad.push(`app/package-lock.json (${name}): ${have ?? '(none)'} != ${version}`);
    }
  }
  return bad;
}

const xyz = (v) => (/^(\d+\.\d+\.\d+)/.exec(v) || [])[1];

/** Null when whatsnew.json lists a release for `version` (by x.y.z, with an entries list), else what is wrong (tour C13). */
function whatsNewProblem(root, version) {
  let file;
  try { file = readJson(path.join(root, WHATSNEW)); } catch (e) { return `${WHATSNEW}: cannot read it (${e.code || e.message})`; }
  if (!file || !Array.isArray(file.releases)) return `${WHATSNEW}: no releases list`;
  const want = xyz(version);
  if (file.releases.some((r) => r && typeof r.version === 'string' && xyz(r.version) === want && Array.isArray(r.entries))) return null;
  return `${WHATSNEW} has no release ${version}: add {"version": "${version}", "entries": []} to its releases, `
    + 'with an entry per change worth a card ("entries": [] when none is)';
}

function main(args = process.argv.slice(2), { root = path.resolve(__dirname, '..'), log = console.log, err = console.error } = {}) {
  const version = args.find((a) => !a.startsWith('--'));
  if (!version || !SEMVER.test(version)) { err('usage: node tools/bump-version.js <x.y.z> [--check]'); return 2; }
  const whatsNew = whatsNewProblem(root, version);
  if (args.includes('--check')) {
    const bad = checkFiles(root, version);
    for (const b of bad) err(`version mismatch: ${b}`);
    log(bad.length ? `bump-version: ${bad.length} mismatch(es) — run: npm run version:bump -- ${version}` : `bump-version: all surfaces at ${version}`);
    if (whatsNew) err(`bump-version: ${whatsNew} (tour C13)`);
    return bad.length || whatsNew ? 1 : 0;
  }
  // What's new first, so a bump that cannot finish writes nothing (tour C13).
  if (whatsNew) { err(`bump-version: ${whatsNew} (tour C13); nothing was changed`); return 1; }
  const out = bumpFiles(root, version);
  for (const f of out.updated) log(`bumped ${f}`);
  for (const f of out.skipped) log(`skipped ${f} (missing)`);
  log('next: npm install --package-lock-only --ignore-scripts, and the same in app/');
  return require('./changelog.js').main(['roll', version], { root, log, err }) === 0 ? 0 : 1;
}

if (require.main === module) process.exit(main());
module.exports = { bumpFiles, checkFiles, whatsNewProblem, main, FILES };
